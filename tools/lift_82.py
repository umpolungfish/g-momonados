print("  Γ3 = q3")
print("  Γ2 = q2 ∨ q3")
print("  Γ1 = q1 ∨ q2 ∨ q3 = A")
print()
print("82C path invariance: TRUE")
print("  AREV-before-every-pop and AREV-only-before-first-pop")
print("  give the same FFUSE3 ladders for all measured permutations.")
print()
